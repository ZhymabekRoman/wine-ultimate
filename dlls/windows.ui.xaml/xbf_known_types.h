/* XBF v2 built-in (a.k.a. "known") type and property index tables.
 *
 * XBF v2 node streams reference the framework types and properties that are not
 * present in the file's own type/property tables by a hardcoded 16-bit index with
 * the high bit set (KnownTypeIndex / KnownPropertyIndex).  The index -> name
 * mapping below is clean-room data: it comes from the public XBF specifications
 * and from the MIT-licensed chausner/XbfTools "XbfFrameworkTypes" table, which
 * extracts it from the XBF writer's metadata, plus the ids verified at runtime
 * against the Calculator, Store and Notepad XBF streams.
 */
